import { createContext, useCallback, useContext, useEffect, useMemo, useRef, useState, type ReactNode } from "react";
import type { PhotoAsset } from "../lib/local-repository";
import { selectBackend } from "../lib/backend-factory";
import { applyMediaUrls } from "../lib/supabase-mappers";
import { deriveStatistics } from "../lib/selectors";
import type { AppState, AppUser, Trip } from "../types/domain";

interface AppDataValue {
  ready: boolean;
  /** True when data lives in the hosted Supabase backend rather than this browser. */
  remote: boolean;
  storageError: string;
  user: AppUser | null;
  state: AppState | null;
  statistics: ReturnType<typeof deriveStatistics> | null;
  /** Resolves `verifyEmail: true` when the account exists but the address must be confirmed before sign-in. */
  register(name: string, email: string, password: string): Promise<{ verifyEmail: boolean }>;
  signIn(email: string, password: string): Promise<void>;
  signOut(): Promise<void>;
  requestPasswordReset(email: string): Promise<void>;
  completePasswordReset(newPassword: string): Promise<void>;
  /** Resolves with warnings (for example photos that failed to upload) when the trip itself was saved. */
  saveTrip(trip: Trip, assets?: PhotoAsset[]): Promise<string[]>;
  deleteTrip(tripId: string): Promise<void>;
  toggleTripFavourite(tripId: string): Promise<void>;
  togglePhotoFavourite(photoId: string): Promise<void>;
  toggleBucketList(countryId: string): Promise<void>;
  setFavouriteCountry(countryId?: string): Promise<void>;
  /** Resolves with a notice to show the user when more than a plain save happened. */
  updateProfile(name: string, email: string): Promise<string | undefined>;
  changePassword(currentPassword: string, newPassword: string): Promise<void>;
  deleteAccount(password?: string): Promise<void>;
  /** Present only when exports are generated by the hosted backend. */
  exportData?: () => Promise<Blob>;
}

const AppDataContext = createContext<AppDataValue | null>(null);
const MEDIA_REFRESH_MS = 5 * 60 * 1000;

export function AppDataProvider({ children }: { children: ReactNode }) {
  const [selected] = useState(selectBackend);
  const backend = selected.backend;
  const [ready, setReady] = useState(false);
  const [storageError, setStorageError] = useState(selected.configError ?? "");
  const [user, setUser] = useState<AppUser | null>(null);
  const [state, setState] = useState<AppState | null>(null);
  const [actionError, setActionError] = useState("");
  const stateRef = useRef<AppState | null>(null);
  const lastMediaRefresh = useRef(Date.now());
  stateRef.current = state;

  useEffect(() => {
    if (selected.configError) { setReady(true); return; }
    let active = true;
    const unsubscribe = backend.onSignedOut(() => { if (active) { setUser(null); setState(null); } });
    (async () => {
      try {
        const session = await backend.init();
        if (session && active) { setUser(session.user); setState(session.state); lastMediaRefresh.current = Date.now(); }
      } catch (error) {
        if (active) setStorageError(error instanceof Error ? error.message : "Your atlas could not be opened.");
      } finally { if (active) setReady(true); }
    })();
    return () => { active = false; unsubscribe(); };
  }, [backend, selected.configError]);

  // Private image links expire after ten minutes, so re-sign them while the app is open.
  const userId = user?.id;
  useEffect(() => {
    if (!backend.refreshMedia || !userId) return;
    let active = true;
    const refresh = async () => {
      const photoIds = stateRef.current?.trips.flatMap((trip) => trip.photos.map((photo) => photo.id)) ?? [];
      if (!photoIds.length) return;
      try {
        const urls = await backend.refreshMedia!(photoIds);
        lastMediaRefresh.current = Date.now();
        if (active) setState((current) => current && current.userId === userId ? applyMediaUrls(current, urls) : current);
      } catch { /* The next tick retries; images already on screen are unaffected. */ }
    };
    const timer = window.setInterval(refresh, MEDIA_REFRESH_MS);
    const onVisible = () => { if (document.visibilityState === "visible" && Date.now() - lastMediaRefresh.current > MEDIA_REFRESH_MS) void refresh(); };
    document.addEventListener("visibilitychange", onVisible);
    return () => { active = false; window.clearInterval(timer); document.removeEventListener("visibilitychange", onVisible); };
  }, [backend, userId]);

  useEffect(() => {
    if (!actionError) return;
    const timer = window.setTimeout(() => setActionError(""), 7000);
    return () => window.clearTimeout(timer);
  }, [actionError]);

  // Failed changes leave the on-screen data untouched and tell the user, instead of failing silently.
  const mutate = useCallback(async (operation: (current: AppState) => Promise<AppState>, options: { rethrow?: boolean } = {}) => {
    if (!state) throw new Error("Sign in before changing your atlas.");
    try { setState(await operation(state)); }
    catch (error) {
      setActionError(error instanceof Error ? error.message : "That change couldn’t be saved.");
      if (options.rethrow) throw error;
    }
  }, [state]);

  const value = useMemo<AppDataValue>(() => ({
    ready, remote: backend.kind === "supabase", storageError, user, state,
    statistics: state ? deriveStatistics(state) : null,
    register: async (name, email, password) => {
      const result = await backend.register(name, email, password);
      if (result.status === "verify-email") return { verifyEmail: true };
      setUser(result.session.user); setState(result.session.state);
      return { verifyEmail: false };
    },
    signIn: async (email, password) => { const session = await backend.signIn(email, password); setUser(session.user); setState(session.state); },
    signOut: async () => {
      // Leave the UI immediately; a failed network revoke must not trap the user in a signed-in screen.
      setUser(null); setState(null);
      await backend.signOut().catch(() => undefined);
    },
    requestPasswordReset: (email) => backend.requestPasswordReset(email),
    completePasswordReset: (newPassword) => backend.completePasswordReset(newPassword),
    saveTrip: async (trip, assets = []) => {
      if (!state) throw new Error("Sign in before changing your atlas.");
      const result = await backend.saveTrip(state, trip, assets);
      setState(result.state);
      return result.warnings;
    },
    deleteTrip: (tripId) => mutate((current) => backend.deleteTrip(current, tripId), { rethrow: true }),
    toggleTripFavourite: (tripId) => mutate((current) => backend.toggleTripFavourite(current, tripId)),
    togglePhotoFavourite: (photoId) => mutate((current) => backend.togglePhotoFavourite(current, photoId)),
    toggleBucketList: (countryId) => mutate((current) => backend.toggleBucketList(current, countryId)),
    setFavouriteCountry: (countryId) => mutate((current) => backend.setFavouriteCountry(current, countryId)),
    updateProfile: async (name, email) => {
      if (!user) return undefined;
      const result = await backend.updateProfile(user, name, email);
      setUser(result.user);
      return result.notice;
    },
    changePassword: async (currentPassword, newPassword) => { if (user) await backend.changePassword(user, currentPassword, newPassword); },
    deleteAccount: async (password) => { if (!user) return; await backend.deleteAccount(user, password); setUser(null); setState(null); },
    exportData: backend.exportData ? () => backend.exportData!() : undefined,
  }), [backend, mutate, ready, state, storageError, user]);

  return (
    <AppDataContext.Provider value={value}>
      {children}
      {actionError && (
        <div role="alert" className="fixed left-1/2 top-4 z-[100] flex w-[min(92vw,400px)] -translate-x-1/2 items-start gap-3 rounded-2xl px-4 py-3 shadow-xl" style={{ background: "var(--foreground)", color: "var(--background)", fontSize: "13px" }}>
          <span className="flex-1">{actionError}</span>
          <button type="button" onClick={() => setActionError("")} className="-my-1 -mr-2 flex h-9 w-9 items-center justify-center rounded-full" aria-label="Dismiss message">✕</button>
        </div>
      )}
    </AppDataContext.Provider>
  );
}

export function useAppData() {
  const value = useContext(AppDataContext);
  if (!value) throw new Error("useAppData must be used inside AppDataProvider.");
  return value;
}
