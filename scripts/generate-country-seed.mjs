import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = path.join(root, "supabase/data/geonames-countryInfo.txt");
const outputPath = path.join(root, "supabase/seed.sql");

// 193 UN member states plus the Holy See and the State of Palestine.
const worldTotalCodes = new Set(`
AF AL DZ AD AO AG AR AM AU AT AZ BS BH BD BB BY BE BZ BJ BT BO BA BW BR BN BG BF BI CV KH CM CA CF TD CL CN CO KM CG CD CR CI HR CU CY CZ DK DJ DM DO EC EG SV GQ ER EE SZ ET FJ FI FR GA GM GE DE GH GR GD GT GN GW GY HT HN HU IS IN ID IR IQ IE IL IT JM JP JO KZ KE KI KP KR KW KG LA LV LB LS LR LY LI LT LU MG MW MY MV ML MT MH MR MU MX FM MD MC MN ME MA MZ MM NA NR NP NL NZ NI NE NG MK NO OM PK PW PA PG PY PE PH PL PT QA RO RU RW KN LC VC WS SM ST SA SN RS SC SL SG SK SI SB SO ZA SS ES LK SD SR SE CH SY TJ TZ TH TL TG TO TT TN TR TM TV UG UA AE GB US UY UZ VU VE VN YE ZM ZW VA PS
`.trim().split(/\s+/));

const continentNames = {
  AF: "Africa",
  AN: "Antarctica",
  AS: "Asia",
  EU: "Europe",
  NA: "North America",
  OC: "Oceania",
  SA: "South America",
};

const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const source = await readFile(inputPath, "utf8");
const countries = source
  .split(/\r?\n/)
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => line.split("\t"))
  .filter(([iso]) => iso && !["AN", "CS"].includes(iso))
  .map((columns) => ({
    iso: columns[0],
    iso3: columns[1],
    numeric: columns[2] || null,
    name: columns[4],
    continent: columns[8],
  }))
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

if (worldTotalCodes.size !== 195) {
  throw new Error(`Expected 195 statistics countries, found ${worldTotalCodes.size}`);
}

const availableCodes = new Set(countries.map(({ iso }) => iso));
const missingCodes = [...worldTotalCodes].filter((code) => !availableCodes.has(code));
if (missingCodes.length) {
  throw new Error(`GeoNames source is missing statistics countries: ${missingCodes.join(", ")}`);
}

const rows = countries.map((country, index) => {
  const continentName = continentNames[country.continent];
  if (!continentName) throw new Error(`Unknown continent code ${country.continent}`);
  return `  (${[
    quote(country.iso),
    quote(country.iso3),
    country.numeric ? quote(country.numeric.padStart(3, "0")) : "null",
    quote(country.name),
    quote(country.name),
    quote(country.continent),
    quote(continentName),
    worldTotalCodes.has(country.iso) ? "true" : "false",
    index + 1,
  ].join(", ")})`;
});

const sql = `-- Generated by scripts/generate-country-seed.mjs.
-- Source: GeoNames countryInfo.txt, CC BY 4.0.

update public.countries set is_active = false;

insert into public.countries (
  iso_code,
  iso3_code,
  numeric_code,
  name,
  official_name,
  continent_code,
  continent_name,
  counts_toward_world_total,
  sort_order
)
values
${rows.join(",\n")}
on conflict (iso_code) do update set
  iso3_code = excluded.iso3_code,
  numeric_code = excluded.numeric_code,
  name = excluded.name,
  official_name = excluded.official_name,
  continent_code = excluded.continent_code,
  continent_name = excluded.continent_name,
  counts_toward_world_total = excluded.counts_toward_world_total,
  sort_order = excluded.sort_order,
  is_active = true,
  updated_at = now();
`;

await writeFile(outputPath, sql, "utf8");
console.log(`Wrote ${countries.length} active countries and territories to ${outputPath}`);

// The web app uses the same list so every selectable place exists in the database.
const webOutputPath = path.join(root, "src/app/data/countries.generated.ts");
const records = countries.map((country) =>
  `  [${JSON.stringify(country.iso)}, ${JSON.stringify(country.name.trim())}, ${JSON.stringify(country.continent)}, ${worldTotalCodes.has(country.iso) ? 1 : 0}],`);
await writeFile(webOutputPath, `// Generated by scripts/generate-country-seed.mjs. Do not edit by hand.
// Source: GeoNames countryInfo.txt, CC BY 4.0. Matches supabase/seed.sql exactly.

/** [ISO 3166-1 alpha-2 code, name, GeoNames continent code, 1 if it counts toward the 195-country total]. */
export type CountryRecord = readonly [id: string, name: string, continentCode: string, countsTowardTotal: 0 | 1];

export const COUNTRY_RECORDS: readonly CountryRecord[] = [
${records.join("\n")}
];
`, "utf8");
console.log(`Wrote ${countries.length} countries to ${webOutputPath}`);
